package scraper.core;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import scraper.annotations.NodePlugin;
import scraper.annotations.NotNull;
import scraper.api.FlowMap;
import scraper.api.FunctionalNode;
import scraper.api.FunctionalNodeContainer;
import scraper.api.NodeException;
import scraper.api.flow.impl.FlowMapImpl;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static java.lang.System.Logger.Level.DEBUG;

/**
 * A {@link FunctionalNode} that delegates to an external executable via
 * {@code fork+exec}. The wire protocol is intentionally minimal:
 *
 * <pre>
 *   parent -&gt; child  : JSON { flowMap: {...}, spec: {...} } on stdin, EOF
 *   child  -&gt; parent : JSON { flowMap: {...} } on stdout, exit 0
 *   on error         : non-zero exit, stderr carries diagnostics
 * </pre>
 *
 * The child is expected to re-init its own {@code @FlowKey} fields from
 * {@code spec} (the workflow YAML fragment for this node instance) — the
 * wrappers generated by {@code node-build.sh} do exactly that.
 *
 * <p>The child also responds to a one-shot {@code --schema} probe with its
 * {@code @FlowKey} input/output schema as JSON, which lets the host type
 * checker reason about the node's outputs without loading its class.
 *
 * <p>Intentional non-features: no cross-call state, no host services, no
 * stream semantics. Any of those go through the core node path.
 */
@NodePlugin(value = "0.1.0", customFlowAfter = true)
public class SubprocessNode implements FunctionalNode {

    private static final System.Logger log = System.getLogger("SubprocessNode");
    private static final ObjectMapper JSON = new ObjectMapper();

    public static final class FieldSchema {
        public String name;
        public String type;
        public FieldSchema() {}
        public FieldSchema(String name, String type) { this.name = name; this.type = type; }
    }

    public static final class Schema {
        public List<FieldSchema> inputs = List.of();
        public List<FieldSchema> outputs = List.of();
        /** Names of type variables mentioned in {@code inputs}/{@code outputs}
         *  type strings. Empty for nodes whose {@code @FlowKey} fields are
         *  fully concrete (the common case). When non-empty, the host parses
         *  these identifiers as {@code TypeVariable}s rather than classes and
         *  alpha-renames them per node-instance. */
        public List<String> typeVariables = List.of();
    }

    private final @NotNull Path executable;
    private final @NotNull String type;
    private volatile Schema schema;

    public SubprocessNode(@NotNull Path executable, @NotNull String type) {
        this.executable = executable;
        this.type = type;
    }

    /** The node's @FlowKey schema as reported by the helper binary. Probed on
        first access via {@code <binary> --schema}, then cached. */
    public @NotNull Schema getSchema() {
        Schema s = schema;
        if (s != null) return s;
        synchronized (this) {
            if (schema != null) return schema;
            try {
                schema = probeSchema();
            } catch (IOException | InterruptedException e) {
                log.log(System.Logger.Level.WARNING,
                        "Schema probe of subprocess node {0} failed: {1}; "
                                + "type checker will see it as schemaless.", type, e.getMessage());
                schema = new Schema();
            }
            return schema;
        }
    }

    private Schema probeSchema() throws IOException, InterruptedException {
        Process p = new ProcessBuilder(executable.toString(), "--schema")
                .redirectErrorStream(false).start();
        p.getOutputStream().close();
        byte[] stdout = readAll(p.getInputStream());
        byte[] stderr = readAll(p.getErrorStream());
        int rc = p.waitFor();
        if (rc != 0) {
            throw new IOException("subprocess --schema exited " + rc + ": " + new String(stderr));
        }
        return JSON.readValue(stdout, new TypeReference<Schema>() {});
    }

    @Override
    public void modify(@NotNull FunctionalNodeContainer n, @NotNull FlowMap o) {
        Map<String, ?> spec = n.getNodeConfiguration();
        Map<String, Object> privateMap = flowPrivateMap(o);

        Map<String, Object> request = new LinkedHashMap<>();
        request.put("flowMap", privateMap);
        request.put("spec", spec);

        Map<String, Object> response;
        try {
            response = invoke(request);
        } catch (IOException | InterruptedException e) {
            throw new NodeException(e, "Subprocess node " + type + " (" + executable + ") failed");
        }

        Object returnedFlow = response.get("flowMap");
        if (!(returnedFlow instanceof Map<?, ?>)) {
            throw new NodeException("Subprocess node " + type
                    + " returned malformed response: missing 'flowMap' object");
        }

        // Replace the parent's live map with whatever the subprocess produced.
        privateMap.clear();
        @SuppressWarnings("unchecked")
        Map<String, Object> updated = (Map<String, Object>) returnedFlow;
        privateMap.putAll(updated);
    }

    private Map<String, Object> invoke(Map<String, Object> request)
            throws IOException, InterruptedException {
        byte[] payload = JSON.writeValueAsBytes(request);
        log.log(DEBUG, "exec {0} ({1} bytes in)", executable, payload.length);

        ProcessBuilder pb = new ProcessBuilder(executable.toString())
                .redirectErrorStream(false);
        Process p = pb.start();
        p.getOutputStream().write(payload);
        p.getOutputStream().close();

        byte[] stdout = readAll(p.getInputStream());
        byte[] stderr = readAll(p.getErrorStream());

        int rc = p.waitFor();
        if (rc != 0) {
            throw new IOException("subprocess exited " + rc + ": "
                    + new String(stderr));
        }
        @SuppressWarnings("unchecked")
        Map<String, Object> parsed = JSON.readValue(stdout, Map.class);
        return parsed;
    }

    private static byte[] readAll(java.io.InputStream in) throws IOException {
        ByteArrayOutputStream buf = new ByteArrayOutputStream();
        in.transferTo(buf);
        return buf.toByteArray();
    }

    private static Map<String, Object> flowPrivateMap(FlowMap o) {
        if (o instanceof FlowMapImpl) {
            return ((FlowMapImpl) o).getPrivateMap();
        }
        throw new IllegalStateException(
                "SubprocessNode requires FlowMapImpl; got " + o.getClass().getName());
    }
}
